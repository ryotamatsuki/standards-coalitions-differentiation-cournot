#!/usr/bin/env python3
"""Stage13 exposition only: deterministic canonical V2b government consent comparison.

Sample-point illustration at g=1/20, not proof of all-g assertions.
SW design held fixed is a DIFFERENT restricted-strategy government game.
Authoritative continuation at fully endogenous design comes from the frozen
Stage7 evaluator; pointwise C/AB and frozen calculation are checked against
Stage4A rational interval certificate outcomes.
"""
import argparse
import sys
from pathlib import Path
import numpy as np

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/"verification"))
from v2b_stage07_welfare_institutions import BASE, equilibrium  # noqa: E402

OUT=ROOT/"paper"/"generated"/"consent_table.tex"
G=1/20

def frozen_welfare(regime, g, x):
    """Re-evaluate the welfare primitive without calling a design solver."""
    eta,rho,kappa=BASE
    H=np.eye(3)
    if regime in ("SU","IS"):
        H[0,1]=H[1,0]=g
    if regime=="IS":
        H[0,2]=H[2,0]=H[1,2]=H[2,1]=g
    X=np.eye(3)
    for i in range(3):
        for j in range(i+1,3):
            X[i,j]=X[j,i]=(x[i]+x[j])/2
    B=rho*H+(1-rho)*X
    M=np.eye(3)+B-eta*H
    q=np.linalg.solve(M,np.ones(3))
    return (q@B@q)/2+3*q*q-kappa*(1-x)**2/2

def render():
    sw=equilibrium("SW",0,BASE)
    su=equilibrium("SU",G,BASE)
    intl=equilibrium("IS",G,BASE)
    fsu=frozen_welfare("SU",G,sw["x"])
    fi=frozen_welfare("IS",G,sw["x"])
    S=sw["W"][0]
    endogenous=[su["W"][0]-S,intl["W"][2]-su["W"][2],
                intl["W"][0]-S]
    frozen=[fsu[0]-S,fi[2]-fsu[2],fi[0]-S]
    # Regression anchors individually reproduced from Stage4A/Stage11.
    want_endo=(-0.000473474171,-0.001246547234,0.016934627905)
    want_frozen=(0.000272381637,0.000234616668,0.019318615645)
    for actual,expected in list(zip(endogenous,want_endo))+list(zip(frozen,want_frozen)):
        if abs(actual-expected)>3e-9:
            raise AssertionError(f"Stage13 consent table drift: {actual} vs {expected}")
    if not(endogenous[0]<0 and endogenous[1]<0 and endogenous[2]>0
           and all(z>0 for z in frozen)):
        raise AssertionError("Consent/welfare qualitative reversal missing")
    r1="Endogenous design & "+" & ".join(f"{z:+.9f}" for z in endogenous)+r" \\"
    r2="Frozen SW design & "+" & ".join(f"{z:+.9f}" for z in frozen)+r" \\"
    return (
      "% GENERATED by production/scripts/generate_consent_table.py; DO NOT EDIT.\n"
      "% Sample point only: all-g claims require separate Stage4A interval proofs.\n"
      "\\begin{table}[!htbp]\n\\centering\n"
      "\\caption{Country participation margins at $g=1/20$ (canonical $\\phi(x)=x$)}\n"
      "\\label{tab:v2b-consent-margins}\n"
      "\\begin{tabular}{lrrr}\n\\hline\n"
      "Firm design & $m(g)-s$ & $i(g)-o(g)$ & $i(g)-s$ \\\\\n\\hline\n"
      +r1+"\n"+r2+"\n\\hline\n\\end{tabular}\n"
      "\\par\\smallskip\n"
      "\\begin{minipage}{0.96\\linewidth}\\footnotesize "
      "Positive first/second columns favor forming the initial bilateral union / outsider accession, "
      "respectively; the last column compares a hypothetical international regime with fragmentation. "
      "Frozen means an alternative restricted-strategy game with every firm's design fixed at its true "
      "SW Nash value at every policy history, not another Nash outcome of the original game. "
      "Rounded point values illustrate signs at this depth only; all-depth exclusion and the "
      "frozen global SU policy envelope are certified separately by rational interval methods."
      "\\end{minipage}\n\\end{table}\n"
    )

def main():
    p=argparse.ArgumentParser()
    g=p.add_mutually_exclusive_group(required=True)
    g.add_argument("--write",action="store_true")
    g.add_argument("--check",action="store_true")
    a=p.parse_args()
    txt=render()
    if a.write:
        OUT.parent.mkdir(parents=True,exist_ok=True)
        OUT.write_text(txt,encoding="utf-8",newline="\n")
        print("WROTE",OUT.relative_to(ROOT))
    elif not OUT.is_file() or OUT.read_text(encoding="utf-8")!=txt:
        raise SystemExit("Stage13 generated consent table is missing/stale; run make table")
    else:
        print("VERIFIED",OUT.relative_to(ROOT),"against equilibrium evaluator and exact anchors")
if __name__=="__main__":
    main()
